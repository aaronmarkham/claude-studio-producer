"""Unit tests for core/ingest/photos.py.

Exercises the fixtures generated by tests/fixtures/photos/make_fixtures.py — see
that module for the fixture layout and the constants (timestamp, GPS coordinates,
EXIF offsets) asserted against below.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import pytest

from core.ingest.models import LocationSource, TzSource
from core.ingest.photos import (
    camera_key,
    cluster_by_camera,
    load_photos,
    resolve_sidecar,
)

FIXTURES = Path(__file__).parent.parent / "fixtures" / "photos" / "data"

# Kept in sync with tests/fixtures/photos/make_fixtures.py
SIDECAR_UTC = datetime.fromtimestamp(1683191553, tz=timezone.utc)
SIDECAR_LAT = 38.682
SIDECAR_LON = -122.395


def _by_name(photos, name):
    for photo in photos:
        if photo.path.name == name:
            return photo
    raise AssertionError(f"no fixture photo named {name!r} in {[p.path.name for p in photos]}")


