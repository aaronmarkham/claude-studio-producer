class TestScreenshotDetection:
    def test_screenshots_excluded_by_default(self):
        photos = load_photos(FIXTURES / "screenshots")
        names = {p.path.name for p in photos}
        assert "screenshot.jpg" not in names
        assert "not_screenshot.jpg" in names

    def test_screenshots_included_with_flag(self):
        photos = load_photos(FIXTURES / "screenshots", include_screenshots=True)
        screenshot = _by_name(photos, "screenshot.jpg")
        not_screenshot = _by_name(photos, "not_screenshot.jpg")
        assert screenshot.is_screenshot is True
        assert not_screenshot.is_screenshot is False


