class TestSidecarPriority:
    def test_sidecar_timestamp_is_utc_and_tagged(self):
        photos = load_photos(FIXTURES / "sidecars", include_screenshots=True)
        photo = _by_name(photos, "IMG_4471.jpg")
        assert photo.taken_utc == SIDECAR_UTC
        assert photo.taken_utc.tzinfo is not None
        assert photo.tz_offset_source == TzSource.SIDECAR

    def test_sidecar_geo_populates_lat_lon(self):
        photos = load_photos(FIXTURES / "sidecars", include_screenshots=True)
        photo = _by_name(photos, "IMG_4471.jpg")
        assert photo.lat == pytest.approx(SIDECAR_LAT)
        assert photo.lon == pytest.approx(SIDECAR_LON)
        assert photo.location_source == LocationSource.SIDECAR

    def test_zero_zero_geodata_is_treated_as_absent(self):
        photos = load_photos(FIXTURES / "sidecars", include_screenshots=True)
        photo = _by_name(photos, "IMG_4476_zerogeo.jpg")
        # The sidecar's timestamp is still good even though its geoData is empty.
        assert photo.taken_utc == SIDECAR_UTC
        assert photo.lat is None
        assert photo.lon is None
        assert photo.location_source == LocationSource.NONE

    def test_sidecar_path_is_recorded_on_the_photo(self):
        photos = load_photos(FIXTURES / "sidecars", include_screenshots=True)
        photo = _by_name(photos, "IMG_4471.jpg")
        assert photo.sidecar_path == FIXTURES / "sidecars" / "IMG_4471.jpg.json"


