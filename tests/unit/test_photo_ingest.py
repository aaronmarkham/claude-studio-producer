class TestCameraAttribution:
    def test_camera_key_full_fingerprint(self):
        key = camera_key({"Make": "Apple", "Model": "iPhone 14 Pro", "BodySerialNumber": "ABC123"})
        assert key == "Apple/iPhone 14 Pro/ABC123"

    def test_camera_key_missing_serial_is_stable(self):
        key_a = camera_key({"Make": "Apple", "Model": "iPhone 12", "BodySerialNumber": None})
        key_b = camera_key({"Make": "Apple", "Model": "iPhone 12"})
        assert key_a == key_b == "Apple/iPhone 12"

    def test_camera_key_all_absent_is_unknown(self):
        assert camera_key({}) == "unknown"
        assert camera_key({"Make": None, "Model": None, "BodySerialNumber": None}) == "unknown"

    def test_cluster_by_camera_partitions_mixed_folder(self):
        photos = load_photos(FIXTURES / "cameras", include_screenshots=True)
        clusters = cluster_by_camera(photos)

        assert len(clusters["Apple/iPhone 14 Pro/ABC123"]) == 2
        assert len(clusters["Apple/iPhone 12"]) == 2  # no-serial camera still clusters
        assert len(clusters["Canon/EOS R6/XYZ999"]) == 1
        assert len(clusters["unknown"]) == 1

    def test_credited_camera_gets_credit(self):
        photos = load_photos(
            FIXTURES / "cameras",
            include_screenshots=True,
            credits={"Apple/iPhone 14 Pro/ABC123": "Aaron"},
        )
        photo = _by_name(photos, "apple_a.jpg")
        assert photo.credit == "Aaron"

    def test_uncredited_camera_stays_none(self):
        photos = load_photos(
            FIXTURES / "cameras",
            include_screenshots=True,
            credits={"Apple/iPhone 14 Pro/ABC123": "Aaron"},
        )
        canon_photo = _by_name(photos, "canon_a.jpg")
        unknown_photo = _by_name(photos, "no_camera.jpg")
        assert canon_photo.credit is None
        assert unknown_photo.credit is None

    def test_no_credits_mapping_leaves_everyone_uncredited(self):
        photos = load_photos(FIXTURES / "cameras", include_screenshots=True)
        assert all(photo.credit is None for photo in photos)


