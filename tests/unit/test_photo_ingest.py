class TestExifOnly:
    def test_exif_only_sets_local_naive_leaves_utc_none(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "exif_only.jpg")
        assert photo.taken_local_naive == datetime(2023, 6, 15, 14, 30, 0)
        assert photo.taken_local_naive.tzinfo is None
        assert photo.taken_utc is None
        assert photo.tz_offset_source == TzSource.UNKNOWN

    def test_exif_offset_plus_resolves_utc(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "exif_offset_plus.jpg")
        # local 14:30 at +02:00 -> 12:30 UTC
        assert photo.taken_utc == datetime(2023, 6, 15, 12, 30, 0, tzinfo=timezone.utc)
        assert photo.tz_offset_source == TzSource.EXIF_OFFSET
        assert photo.tz_offset_minutes == 120

    def test_exif_offset_minus_resolves_utc(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "exif_offset_minus.jpg")
        # local 14:30 at -05:00 -> 19:30 UTC
        assert photo.taken_utc == datetime(2023, 6, 15, 19, 30, 0, tzinfo=timezone.utc)
        assert photo.tz_offset_source == TzSource.EXIF_OFFSET
        assert photo.tz_offset_minutes == -300

    def test_gps_south_and_west_are_negative(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "gps_south_west.jpg")
        assert photo.exif_lat < 0
        assert photo.exif_lon < 0
        assert photo.exif_lat == pytest.approx(-38.6517, abs=1e-3)
        assert photo.exif_lon == pytest.approx(-122.395, abs=1e-3)

    def test_gps_north_and_east_are_positive(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "gps_north_east.jpg")
        assert photo.exif_lat > 0
        assert photo.exif_lon > 0
        assert photo.exif_lat == pytest.approx(38.6517, abs=1e-3)
        assert photo.exif_lon == pytest.approx(122.395, abs=1e-3)

    def test_exif_gps_also_fills_lat_lon_with_exif_source(self):
        photos = load_photos(FIXTURES / "exif", include_screenshots=True)
        photo = _by_name(photos, "gps_north_east.jpg")
        assert photo.lat == photo.exif_lat
        assert photo.lon == photo.exif_lon
        assert photo.location_source == LocationSource.EXIF


