# --------------------------------------------------------------------------- #

class TestPhotoId:
    def test_identical_bytes_yield_identical_id(self):
        photos = load_photos(FIXTURES / "hashes", include_screenshots=True)
        original = _by_name(photos, "original.jpg")
        duplicate = _by_name(photos, "duplicate.jpg")
        assert original.photo_id == duplicate.photo_id
        assert original.path != duplicate.path

    def test_different_bytes_yield_different_id(self):
        photos = load_photos(FIXTURES / "hashes", include_screenshots=True)
        original = _by_name(photos, "original.jpg")
        different = _by_name(photos, "different.jpg")
        assert original.photo_id != different.photo_id

    def test_photo_id_is_stable_across_reloads(self):
        first = load_photos(FIXTURES / "hashes", include_screenshots=True)
        second = load_photos(FIXTURES / "hashes", include_screenshots=True)
        first_ids = {p.path.name: p.photo_id for p in first}
        second_ids = {p.path.name: p.photo_id for p in second}
        assert first_ids == second_ids


