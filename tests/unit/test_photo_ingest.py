class TestResolveSidecar:
    def test_exact_match(self):
        photo = FIXTURES / "sidecars" / "IMG_4471.jpg"
        sidecar = resolve_sidecar(photo)
        assert sidecar == FIXTURES / "sidecars" / "IMG_4471.jpg.json"

    def test_supplemental_metadata_match(self):
        photo = FIXTURES / "sidecars" / "IMG_4472.jpg"
        sidecar = resolve_sidecar(photo)
        assert sidecar == FIXTURES / "sidecars" / "IMG_4472.jpg.supplemental-metadata.json"

    def test_truncated_match(self):
        photo = FIXTURES / "sidecars" / "IMG_4473.jpg"
        sidecar = resolve_sidecar(photo)
        assert sidecar == FIXTURES / "sidecars" / "IMG_4473.jp.json"

    def test_duplicate_suffixed_match(self):
        photo = FIXTURES / "sidecars" / "IMG_4474(1).jpg"
        sidecar = resolve_sidecar(photo)
        assert sidecar == FIXTURES / "sidecars" / "IMG_4474(1).jpg.json"

    def test_case_mismatched_extension_match(self):
        photo = FIXTURES / "sidecars" / "img_4475.heic"
        sidecar = resolve_sidecar(photo)
        assert sidecar == FIXTURES / "sidecars" / "IMG_4475.HEIC.json"

    def test_no_sidecar_returns_none(self):
        photo = FIXTURES / "exif" / "exif_only.jpg"
        assert resolve_sidecar(photo) is None


